package com.civicfix.platform.users.enums;

/**
 * Standardized system roles for Role-Based Access Control (RBAC).
 * Supports at minimum: CITIZEN, EMPLOYEE, SUPERVISOR, DEPARTMENT_MANAGER, ADMIN, FIELD_WORKER.
 */
public enum RoleType {
    ROLE_CITIZEN,
    ROLE_EMPLOYEE,
    ROLE_SUPERVISOR,
    ROLE_DEPARTMENT_MANAGER,
    ROLE_ADMIN,
    ROLE_FIELD_WORKER,
    ROLE_OPERATOR,
    ROLE_OFFICER,
    ROLE_DEPT_ADMIN,
    ROLE_SUPER_ADMIN
}
